/* The stub, then jmp [rip] back to the game after the replaced bytes. */
static inline unsigned gow3_switch_build_stub(unsigned char *out, const Gow3SwitchSite *site, uintptr_t state,
                                              uintptr_t resume) {
    static const unsigned char jump[] = {0xff,0x25,0,0,0,0}; /* jmp [rip+0] */
    memcpy(out, site->stub, site->stub_length);
    memcpy(out + site->state_at, &state, 8);
    memcpy(out + site->stub_length, jump, sizeof(jump));
    memcpy(out + site->stub_length + sizeof(jump), &resume, 8);
    return site->stub_length + sizeof(jump) + 8;
}
