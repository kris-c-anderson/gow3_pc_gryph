/* Switch attacks, diagnostic build (GOW3_SWITCH_ATTACKS=1). Changes nothing in the game: seven
 * hooks copy what Kratos' move system does with the branches to the switch attacks into a ring of
 * records, and runtime_pad.c writes them to the log next to the pad's L1, Cross and d-pad. Offsets
 * as found in a v01.02 build; builds are found by signature.
 *
 * - weapon check 0xeb5b0 (rdi stats, rsi branch, edx weapon): entry notes stats and weapon, exit
 *   records the result for branches to a weapon (branch +0x2f 0x10..0x13);
 * - branch test 0xec0e0 (rbx branch, stack args pressed/... at [rbp+0x10..0x40]): exit records
 *   branches to a weapon, and any branch a pressed button passes;
 * - input queue 0xec660 (rdi move state, rsi branch, xmm0): every branch buffered;
 * - d-pad 0x6b240, weapon applied 0x6ffe0, SCR_EnableWeapon's select 0x6b5b0 (rdi stats): every
 *   call with its arguments and caller.
 * The stubs are assembled from tools/switch_diag_stubs.s. */
enum { GOW3_SWITCH_SITES = 7, GOW3_SWITCH_SLOT = 512, GOW3_SWITCH_RING = 1024 };
enum { GOW3_SWITCH_EVAL = 1, GOW3_SWITCH_CHECK = 2, GOW3_SWITCH_QUEUE = 3, GOW3_SWITCH_DPAD = 4,
       GOW3_SWITCH_APPLY = 5, GOW3_SWITCH_SELECT = 6 };

typedef struct {
    uint32_t seq;   /* index + 1 once written */
    uint8_t kind;
    uint8_t pad[3];
    uint64_t q[15];
} Gow3SwitchRecord;
typedef struct {
    uint32_t head;          /* records claimed */
    uint32_t pad0;
    uint64_t image;         /* +8 */
    uint64_t eval_return;   /* +16: 0xec8aa, the branch test called from the move's branch loop */
    uint64_t check_stats;   /* +24 */
    uint32_t check_weapon;  /* +32 */
    uint32_t pad1[7];
    Gow3SwitchRecord records[GOW3_SWITCH_RING];  /* +64 */
} Gow3SwitchState;
#ifdef __cplusplus
static_assert(sizeof(Gow3SwitchRecord) == 128 && offsetof(Gow3SwitchState, records) == 64 &&
              offsetof(Gow3SwitchState, check_weapon) == 32, "stubs address the fields directly");
#else
_Static_assert(sizeof(Gow3SwitchRecord) == 128 && offsetof(Gow3SwitchState, records) == 64 &&
               offsetof(Gow3SwitchState, check_weapon) == 32, "stubs address the fields directly");
#endif

